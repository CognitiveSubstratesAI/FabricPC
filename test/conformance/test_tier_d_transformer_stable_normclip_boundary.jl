# ACTUAL GATING (report() above is diagnostic). TOLERANCE: rtol=atol=1f-4 -- Float32 BLAS/XLA
# associativity across multiple chained inference steps, same convention every Tier D test in
# this repo uses. The discrete clip/no-clip assertion is the point of this file: it fails if
# Julia and upstream disagree on the BRANCH, not just the clipped value's numerical closeness.
@testset "Tier D conformance (upstream JAX FabricPC, transformer-LM, InferenceSGDNormClip boundary-straddle, max_norm=2.5, rtol/atol 1e-4)" begin
    @testset "value comparisons" begin
        for (name, a, b) in pairs_ncb
            @test allclose_dt(a, b)
        end
    end
    @testset "discrete clip/no-clip decision agreement at near-boundary points" begin
        @test !isempty(near_boundary)  # the whole point of this fixture: it must actually straddle
        for (step, s, n, ratio, clips) in near_boundary
            # same per-sample L2-norm-over-non-batch-dims formula run_pipeline used for Julia's
            # own norm_log, applied here to the FIXTURE's (upstream) latent_grad array instead --
            # an independent recomputation, not a re-read of Julia's own already-checked value.
            g_fix = FIX_NCB["relax$(lpad(step, 2, '0'))_skip_0_latent_grad"]
            fixture_norm = sqrt(
                sum(abs2, view(g_fix, s, ntuple(_ -> Colon(), ndims(g_fix) - 1)...))
            )
            fixture_clips = (fixture_norm / MAX_NORM_NCB) > 1.0f0
            @test clips == fixture_clips
        end
    end
end
