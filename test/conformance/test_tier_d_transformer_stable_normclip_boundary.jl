const FIXDIR = joinpath(@__DIR__, "fixtures")
const FIX_NCB = npzread(joinpath(FIXDIR, "tier_d_transformer_stable_normclip_boundary.npz"))
const FIX_SGD_NCB_XCHECK = npzread(joinpath(FIXDIR, "tier_d_transformer_stable_sgd.npz"))  # params0/batch cross-check only

const B, S, V, E, H = 3, 8, 10, 8, 2
const ETA_INFER = 0.01f0
const INFER_STEPS = 12
const MAX_NORM_NCB = 2.5f0
const NC_EPS = 1.0f-8

row_dt(v) = reshape(Float32.(v), 1, :)

const TIER_DT_FULL_NODES = ("embed", "transformer_0", "skip_0", "output")

# ---------------------------------------------------------------------------------------
# Sanity: params0/batch must be byte-identical to the sibling stable fixtures (single
# un-forked RNG split() stream shared by all tier_d_transformer_stable_* generators).
# ---------------------------------------------------------------------------------------
function check_shared_params0_batch()
    nmismatch = 0
    for k in keys(FIX_SGD_NCB_XCHECK)
        ks = String(k)
        if startswith(ks, "params0_") || startswith(ks, "batch_")
            a = FIX_SGD_NCB_XCHECK[ks]
            b = FIX_NCB[ks]
            if a != b
                println("  MISMATCH vs sibling SGD fixture at key=$ks")
                nmismatch += 1
            end
        end
    end
    println("params0/batch byte-identity vs tier_d_transformer_stable_sgd.npz: ",
        nmismatch == 0 ? "OK (all match)" : "$(nmismatch) MISMATCHES")
    return nmismatch
end

