# Wired into runtests.jl UNGATED alongside test_tier_d_transformer_stable.jl (docs/
# AUDIT_REGISTER.md section 6/C-05) -- promoted after verification, not scratch.
#
# BACKGROUND: test_tier_d_transformer_stable.jl's own InferenceSGDNormClip run (max_norm=1.0,
# vs tier_d_transformer_stable_normclip.npz) passed 523/523 at 1e-4, giving C-05 its first
# conformance-harness coverage -- but a post-hoc check found the actual gradient L2 norms in
# that run never approached max_norm=1.0 anywhere (embed/transformer_0 sat ~0.10-0.27,
# skip_0/output sat ~2.4-33.4): an "all-or-nothing" split with embed/transformer_0 NEVER
# clipping and skip_0/output ALWAYS clipping. The `min(1, max_norm/(norm+eps))` boundary
# branch -- where float32 implementations could plausibly disagree about whether a given
# sample clips -- was never exercised. "Passes" there is coverage BY ABSENCE.
#
# THIS FILE closes that gap against a NEW fixture
# (tier_d_transformer_stable_normclip_boundary.npz, generated by
# scripts/generate_tier_d_transformer_stable_normclip_boundary_fixtures.py) that uses
# max_norm=2.5 -- chosen and SELF-CONSISTENTLY VERIFIED (see that script's docstring for the
# full derivation, including a falsified first hypothesis at max_norm~=0.10) to target
# skip_0's own natural raw-grad range (~2.2-2.98), producing a genuine clip/no-clip straddle:
# sample0 crosses between steps 8->9 (ratio 1.0095 -> 0.9995, a near-exact tie) and sample1
# crosses between steps 1->2 (ratio 1.0058 -> 0.9938) -- both within ~1% of the boundary.
# sample2 stays always-clip (ratio 1.07-1.19) throughout -- not itself a straddle, but doesn't
# need to be; "at least one node, some samples clip/some don't" is satisfied twice over by
# sample0/sample1.
#
# Like the sibling stable-track file, this does NOT use @test/@testset pass-fail gating -- it
# reports pass/fail counts at several tolerances and the worst required tolerance, PLUS a
# dedicated per-(step,node,sample) CLIP-DECISION agreement check at the specific near-boundary
# points identified above: does Julia agree with upstream on the DISCRETE clip/no-clip
# decision (not just the clipped value's numerical closeness)? A hairline float32 rounding
# disagreement right at the threshold would show up here as a "value diff" that's actually a
# BRANCH diff, not ordinary numerical noise -- and would be a materially different, more
# specific finding than the general relaxation-conditioning drift this whole session has been
# investigating.
